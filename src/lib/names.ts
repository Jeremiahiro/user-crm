/**
 * Everyday names vs legal names.
 *
 * preferred_name is what the portal shows in navigation, greetings, and lists.
 * full_name (generated from first / middle / last) stays on official records:
 * exports, DBS, and other formal documents.
 */

export interface NameSource {
  preferred_name?: string | null
  first_name?: string | null
  full_name?: string | null
  /** Session / OAuth display name, used only when no person-name fields are set. */
  name?: string | null
}

function clean(value: string | null | undefined): string {
  return value?.trim() ?? ''
}

/**
 * Name to show in the UI.
 * Preferred name wins. Otherwise the legal full name, then the first name.
 */
export function displayName(person: NameSource | null | undefined): string {
  if (!person) return ''
  const preferred = clean(person.preferred_name)
  if (preferred) return preferred
  const full = clean(person.full_name)
  if (full) return full
  const first = clean(person.first_name)
  if (first) return first
  return clean(person.name)
}

/**
 * Short greeting: preferred name (first word), else given name, else the
 * first word of the legal or account name.
 */
export function greetingName(person: NameSource | null | undefined): string {
  if (!person) return ''
  const preferred = clean(person.preferred_name)
  if (preferred) return preferred.split(/\s+/)[0] ?? preferred
  const first = clean(person.first_name)
  if (first) return first
  const full = clean(person.full_name) || clean(person.name)
  return full.split(/\s+/)[0] ?? full
}

/**
 * Split a Google account name into the NOT NULL people.first_name / last_name
 * columns. full_name is generated by the database and must not be written.
 */
export function splitDisplayName(
  displayNameValue: string | null | undefined,
  email: string,
): { first_name: string; last_name: string } {
  const cleaned = clean(displayNameValue)
  const looksLikeEmail = !cleaned || cleaned.includes('@')
  if (looksLikeEmail) {
    const local = (email.split('@')[0] ?? 'Applicant').replace(/[._-]+/g, ' ').trim()
    const token = local.split(/\s+/).filter(Boolean)[0] ?? 'Applicant'
    return { first_name: token.slice(0, 100), last_name: 'Applicant' }
  }
  const parts = cleaned.split(/\s+/).filter(Boolean)
  const first = parts[0] ?? 'Applicant'
  if (parts.length === 1) {
    return { first_name: first.slice(0, 100), last_name: 'Applicant' }
  }
  return {
    first_name: first.slice(0, 100),
    last_name: parts.slice(1).join(' ').slice(0, 100),
  }
}
